#!/usr/bin/env node
/**
 * Export a building exactly as the browser builds it, for Blender to light.
 *
 * Nothing is modelled twice: this runs the real buildX() against the real
 * PLAN, moves the group to the origin, flattens every solid mesh to an OBJ,
 * and works out the patch of ground the shade lands on.
 *
 *   node tools/export-building.mjs pavilion|farnsworth|savoye out/<name>.obj
 *   node tools/export-building.mjs --check pavilion|farnsworth|savoye   # print the ground rect
 */
import * as THREE from '../vendor-three-0.160.0.js';
import { buildPavilion, PLAN as PAV } from '../pavilion.js';
import { buildFarnsworth } from '../farnsworth.js';
import { buildSavoye } from '../savoye.js';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const BUILDERS = { pavilion: buildPavilion, farnsworth: buildFarnsworth, savoye: buildSavoye };

/** Build one building at the origin; return its solid meshes in group coordinates. */
export function solids(name) {
  const scene = new THREE.Scene();
  const b = BUILDERS[name](THREE, scene, { dark: false });
  b.group.position.set(0, 0, 0);
  scene.updateMatrixWorld(true);
  const out = [];
  scene.traverse((o) => {
    if (!o.isMesh) return;
    if ((o.material?.opacity ?? 1) < 0.6) return;          // glass and water do not shade
    if (o.geometry.type === 'PlaneGeometry' && o.material?.visible === false) return;
    out.push(o.geometry.clone().applyMatrix4(o.matrixWorld));
  });
  return out;
}

/** The ground the shade lands on: the podium for the Pavilion, else the footprint plus 3m, to the half metre. */
export function groundRect(name, geoms = solids(name)) {
  if (name === 'pavilion') {
    const p = PAV.podium;
    return { x0: -p.w / 2, x1: p.w / 2, z0: -p.d / 2, z1: p.d / 2, y: 0 };
  }
  const box = new THREE.Box3();
  for (const g of geoms) { g.computeBoundingBox(); box.union(g.boundingBox); }
  const r = (v, f) => f(v / 0.5) * 0.5;
  return { x0: r(box.min.x - 3, Math.floor), x1: r(box.max.x + 3, Math.ceil),
           z0: r(box.min.z - 3, Math.floor), z1: r(box.max.z + 3, Math.ceil), y: 0 };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const check = args[0] === '--check';
  const name = check ? args[1] : args[0];
  if (!BUILDERS[name]) { console.error('usage: export-building.mjs [--check] pavilion|farnsworth|savoye [out.obj]'); process.exit(2); }
  const geoms = solids(name);
  const rect = groundRect(name, geoms);
  if (check) { console.log(JSON.stringify(rect)); process.exit(0); }

  const out = args[1] || `out/${name}.obj`;
  mkdirSync(path.dirname(out), { recursive: true });
  const lines = [`# ${name} — generated by tools/export-building.mjs`];
  let base = 1;
  geoms.forEach((g, m) => {
    const pos = g.attributes.position, idx = g.index;
    lines.push(`o m${m}`);
    for (let i = 0; i < pos.count; i++) lines.push(`v ${pos.getX(i)} ${pos.getY(i)} ${pos.getZ(i)}`);
    const n = idx ? idx.count : pos.count;
    for (let i = 0; i < n; i += 3) {
      const f = (k) => (idx ? idx.getX(i + k) : i + k) + base;
      lines.push(`f ${f(0)} ${f(1)} ${f(2)}`);
    }
    base += pos.count;
  });
  writeFileSync(out, lines.join('\n') + '\n');
  // The Pavilion is lit by a morning sun and its pools keep their own colour;
  // the others get sky occlusion only, so the baked light never argues with
  // the moving sun's shadow.
  writeFileSync(out.replace(/\.obj$/, '.json'), JSON.stringify({
    ground: rect,
    sun: name === 'pavilion',
    mask: name === 'pavilion' ? PAV.pools : [],
    meshes: geoms.length,
  }, null, 1));
  console.log(`${name}: ${geoms.length} solid meshes → ${out}  ground ${JSON.stringify(rect)}`);
}
