#!/usr/bin/env node
/**
 * Export the Pavilion exactly as the browser builds it, for Blender to bake.
 *
 * The geometry is NOT modelled anywhere else. This runs the same
 * buildPavilion() against the same PLAN the walk controller collides with,
 * flattens every solid mesh to world space, and writes an OBJ plus the
 * bounds of the podium top (the surface the bake lands on).
 *
 *   node tools/pavilion-export.mjs out/pavilion.obj
 */
import * as THREE from '../vendor-three-0.160.0.js';
import { buildPavilion, PLAN } from '../pavilion.js';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const out = process.argv[2] || 'out/pavilion.obj';
mkdirSync(path.dirname(out), { recursive: true });

const scene = new THREE.Scene();
buildPavilion(THREE, scene, { dark: false });
scene.updateMatrixWorld(true);

const lines = ['# pavilion — generated by tools/pavilion-export.mjs'];
let base = 1, meshes = 0;
scene.traverse((o) => {
  if (!o.isMesh) return;
  // Glass and water do not cast light shadows worth baking; keep them out.
  const op = o.material?.opacity ?? 1;
  if (op < 0.6) return;
  const g = o.geometry.clone().applyMatrix4(o.matrixWorld);
  const pos = g.attributes.position;
  const idx = g.index;
  lines.push(`o m${meshes++}`);
  for (let i = 0; i < pos.count; i++) lines.push(`v ${pos.getX(i)} ${pos.getY(i)} ${pos.getZ(i)}`);
  const n = idx ? idx.count : pos.count;
  for (let i = 0; i < n; i += 3) {
    const a = (idx ? idx.getX(i) : i) + base, b = (idx ? idx.getX(i + 1) : i + 1) + base, c = (idx ? idx.getX(i + 2) : i + 2) + base;
    lines.push(`f ${a} ${b} ${c}`);
  }
  base += pos.count;
});
writeFileSync(out, lines.join('\n') + '\n');
const p = PLAN.podium;
writeFileSync(out.replace(/\.obj$/, '.json'), JSON.stringify({
  podiumTop: { x0: -p.w / 2, x1: p.w / 2, z0: -p.d / 2, z1: p.d / 2, y: 0 },
  pools: PLAN.pools,
  meshes,
}, null, 1));
console.log(`pavilion: ${meshes} solid meshes → ${out}`);
